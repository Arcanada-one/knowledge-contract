class ProjectionError(Exception):
    def __init__(self, reason_code: str, message: str, details: dict | None = None):
        super().__init__(message)
        self.reason_code = reason_code
        self.message = message
        self.details = details or {}


def git_blob_sha1(raw: bytes) -> str:
    return hashlib.sha1(b"blob %d\0" % len(raw) + raw).hexdigest()


def dumps_deterministic(obj: Any) -> str:
    return json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def map_validation_errors(errors: list[str]) -> ProjectionError | None:
    for err in errors:
        if "dangling relation" in err or "unknown prerequisite" in err:
            return ProjectionError(REASON_UNKNOWN_ENDPOINT, err, {"errors": errors})
        if "duplicate ID" in err:
            return ProjectionError(REASON_DUPLICATE_ID, err, {"errors": errors})
        if "unknown relation kind" in err:
            return ProjectionError(REASON_UNSUPPORTED_EDGE_KIND, err, {"errors": errors})
        if "scope must remain proposed-reference-view" in err:
            return ProjectionError(REASON_STATUS_RELABEL, err, {"errors": errors})
    if errors:
        return ProjectionError(REASON_VALIDATION_FAILED, errors[0], {"errors": errors})
    return None


def find_authority_claims(obj: Any, path: str = "") -> list[str]:
    found: list[str] = []
    if isinstance(obj, dict):
        for key, value in obj.items():
            here = f"{path}/{key}" if path else key
            if AUTHORITY_FIELD_RE.search(str(key)):
                found.append(here)
            found.extend(find_authority_claims(value, here))
    elif isinstance(obj, list):
        for i, value in enumerate(obj):
            found.extend(find_authority_claims(value, f"{path}/{i}"))
    return found


def reading_link_sccs(relations: list[dict]) -> list[list[str]]:
    """Strongly connected components among reading-interface edges (size > 1 or self-loop)."""
    nodes: set[str] = set()
    adj: dict[str, list[str]] = collections.defaultdict(list)
    for edge in relations:
        if edge.get("kind") != "reading-interface":
            continue
        a, b = edge["from"], edge["to"]
        nodes.add(a)
        nodes.add(b)
        adj[a].append(b)
    index = 0
    stack: list[str] = []
    onstack: set[str] = set()
    indices: dict[str, int] = {}
    low: dict[str, int] = {}
    comps: list[list[str]] = []

    def strongconnect(v: str) -> None:
        nonlocal index
        indices[v] = index
        low[v] = index
        index += 1
        stack.append(v)
        onstack.add(v)
        for w in adj.get(v, []):
            if w not in indices:
                strongconnect(w)
                low[v] = min(low[v], low[w])
            elif w in onstack:
                low[v] = min(low[v], indices[w])
        if low[v] == indices[v]:
            comp: list[str] = []
            while True:
                w = stack.pop()
                onstack.remove(w)
                comp.append(w)
                if w == v:
                    break
            self_loop = any(n in adj.get(n, []) for n in comp)
            if len(comp) > 1 or self_loop:
                comps.append(sorted(comp))

    for n in sorted(nodes):
        if n not in indices:
            strongconnect(n)
    return sorted(comps, key=lambda c: (len(c), c))


def project_nodes(data: dict, input_path: str, blob: str) -> list[dict]:
    sources = data.get("sources", {})
    nodes: list[dict] = []
    for group in GROUPS:
        rows = data.get(group, [])
        for index, node in enumerate(rows):
            identity = node["id"]
            source_key = node.get("source")
            if group == "claims" and source_key is None:
                doc = next((d for d in data.get("documents", []) if d.get("id") == node.get("document")), None)
                source_key = doc.get("source") if isinstance(doc, dict) else None
            pin = None
            if isinstance(source_key, str) and source_key in sources:
                src = sources[source_key]
                pin = {
                    "source_key": source_key,
                    "repository": src.get("repository"),
                    "commit": src.get("commit"),
                }
            entry: dict[str, Any] = {
                "id": identity,
                "group": group,
                "type": node.get("kind"),
                "status": node.get("status"),
                "source_pins": pin,
                "provenance": {
                    "input_path": input_path,
                    "blob": blob,
                    "json_pointer": f"/{group}/{index}",
                },
            }
            if group == "claims":
                entry["premises"] = node.get("premises")
                entry["limits"] = node.get("limits")
                entry["document"] = node.get("document")
                entry["source_location"] = node.get("source_location")
                entry["assessment"] = node.get("assessment")
            if group == "documents":
                entry["title"] = node.get("title")
                entry["path"] = node.get("path")
            if group == "terms":
                entry["label"] = node.get("label")
                entry["path"] = node.get("path")
            if group == "foundation_units":
                entry["title"] = node.get("title")
                entry["path"] = node.get("path")
                entry["document"] = node.get("document")
            if group == "roadmap_nodes":
                entry["source_path"] = node.get("source_path")
                entry["execution_state"] = node.get("execution_state")
            nodes.append(entry)
    nodes.sort(key=lambda n: (GROUPS.index(n["group"]), n["id"]))
    return nodes


def project_relations(data: dict) -> list[dict]:
    edges = []
    for edge in data.get("relations", []):
        item = {
            "from": edge["from"],
            "to": edge["to"],
            "kind": edge["kind"],
            "directed": True,
            "basis": edge.get("basis"),
        }
        if "meaning" in edge:
            item["meaning"] = edge["meaning"]
        edges.append(item)
    edges.sort(key=lambda e: (e["from"], e["kind"], e["to"], e.get("basis") or ""))
    return edges


def project_planning_requires(data: dict) -> list[dict]:
    edges = []
    for node in data.get("roadmap_nodes", []):
        for dep in node.get("requires", []):
            edges.append({
                "from": node["id"],
                "to": dep,
                "kind": "requires",
                "directed": True,
                "family": "planning",
            })
    edges.sort(key=lambda e: (e["from"], e["to"]))
    return edges


def build_projection(data: dict, input_path: str, blob: str) -> dict:
    nodes = project_nodes(data, input_path, blob)
    relations = project_relations(data)
    planning = project_planning_requires(data)
    if len(nodes) != EXPECTED_NODES:
        raise ProjectionError(
            REASON_NODE_COUNT,
            f"expected {EXPECTED_NODES} nodes, got {len(nodes)}",
            {"expected": EXPECTED_NODES, "got": len(nodes)},
        )
    if len(relations) != EXPECTED_RELATIONS:
        raise ProjectionError(
            REASON_RELATION_FAMILY_COUNT,
            f"expected {EXPECTED_RELATIONS} relations, got {len(relations)}",
            {"expected": EXPECTED_RELATIONS, "got": len(relations)},
        )
    if len(planning) != EXPECTED_PLANNING_REQUIRES:
        raise ProjectionError(
            REASON_PLANNING_REQUIRES_COUNT,
            f"expected {EXPECTED_PLANNING_REQUIRES} planning_requires, got {len(planning)}",
            {"expected": EXPECTED_PLANNING_REQUIRES, "got": len(planning)},
        )
    cycles = reading_link_sccs(data.get("relations", []))
    return {
        "record_type": RECORD_TYPE,
        "status": CANDIDATE_STATUS,
        "generated_by": GENERATED_BY,
        "input": {
            "path": input_path,
            "blob": blob,
            "map_record_type": data.get("record_type"),
            "map_status": data.get("status"),
        },
        "disclaimer": {
            "scope": data.get("scope"),
            "not_authority_for": data.get("not_authority_for"),
            "generated_by_line": GENERATED_BY_LINE,
        },
        "legend": LEGEND,
        "semantics": {
            "relation_kinds": data.get("relation_kinds"),
            "required_output_semantics": data.get("required_output_semantics"),
            "preparation_order_semantics": data.get("preparation_order_semantics"),
        },
        "counts": {
            "nodes": len(nodes),
            "relations": len(relations),
            "planning_requires": len(planning),
        },
        "nodes": nodes,
        "layers": {
            "relations": relations,
            "planning_requires": planning,
        },
        "reading_link_cycles": {
            "components": cycles,
            "note": (
                "Strongly connected reading-link components list member ids only "
                "(membership only; no implied edge). Directed paths may exist among "
                "members; actual edges stay only in the relations layer. Not proofs, "
                "inference rules or semantic entailments."
            ),
        },
    }


def index_edges(edges: list[dict]) -> tuple[dict[str, list[dict]], dict[str, list[dict]]]:
    outs: dict[str, list[dict]] = collections.defaultdict(list)
    ins: dict[str, list[dict]] = collections.defaultdict(list)
    for edge in edges:
        outs[edge["from"]].append(edge)
        ins[edge["to"]].append(edge)
    return outs, ins


