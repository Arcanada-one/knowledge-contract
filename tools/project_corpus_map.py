def refuse(err: ProjectionError) -> int:
    payload = {
        "ok": False,
        "reason_code": err.reason_code,
        "message": err.message,
        "details": err.details,
    }
    print(dumps_deterministic(payload), end="")
    return 1


def project_bytes(raw: bytes, input_path: str, expect_blob: str) -> tuple[dict, str, str]:
    blob = git_blob_sha1(raw)
    if blob != expect_blob:
        raise ProjectionError(
            REASON_EXPECT_BLOB_MISMATCH,
            f"git blob {blob} does not match --expect-blob {expect_blob}",
            {"actual_blob": blob, "expect_blob": expect_blob},
        )
    try:
        data = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ProjectionError(REASON_INPUT_ERROR, str(exc)) from exc
    if not isinstance(data, dict):
        raise ProjectionError(REASON_INPUT_ERROR, "map root must be an object")
    if data.get("status") != "proposed-reference-view":
        raise ProjectionError(
            REASON_STATUS_RELABEL,
            f"map status {data.get('status')!r} is not proposed-reference-view",
            {"status": data.get("status")},
        )
    claims = find_authority_claims(data)
    if claims:
        raise ProjectionError(
            REASON_AUTHORITY_CLAIM,
            "input claims runtime/release/permission authority via forbidden field names",
            {"fields": sorted(claims)},
        )
    result = validate(data)
    mapped = map_validation_errors(result.get("errors", []))
    if mapped is not None:
        raise mapped
    if not result.get("structural_valid"):
        raise ProjectionError(REASON_VALIDATION_FAILED, "validator refused the map", result)
    projection = build_projection(data, input_path, blob)
    text = render_text(projection)
    page = render_html(projection)
    return projection, text, page


def write_outputs(out_dir: Path, projection: dict, text: str, page: str) -> dict[str, str]:
    out_dir.mkdir(parents=True, exist_ok=True)
    files = {
        "projection.json": dumps_deterministic(projection).encode("utf-8"),
        "projection.txt": text.encode("utf-8"),
        "projection.html": page.encode("utf-8"),
        "CANDIDATE": (
            "candidate projection of a proposed-reference-view corpus map; "
            "not accepted, not a proof graph, not runtime policy, not Muneral state\n"
        ).encode("utf-8"),
    }
    digests = {}
    for name, content in sorted(files.items()):
        path = out_dir / name
        path.write_bytes(content)
        digests[name] = hashlib.sha256(content).hexdigest()
    return digests


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--map",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "reference/foundations/corpus-map.json",
        help="Path to the corpus map JSON input",
    )
    parser.add_argument(
        "--expect-blob",
        required=True,
        help="Required git blob SHA-1 of the exact input bytes",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path(__file__).resolve().parents[1]
        / "reference/foundations/projections/corpus-map-a7b2fb8c",
        help="Directory for candidate projection outputs",
    )
    parser.add_argument(
        "--stdout-json-only",
        action="store_true",
        help="Write projection JSON to stdout and skip filesystem outputs",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Refuse unless existing --out-dir bytes match a fresh deterministic projection",
    )
    args = parser.parse_args(argv)
    try:
        raw = args.map.read_bytes()
        input_path = args.map.as_posix()
        projection, text, page = project_bytes(raw, input_path, args.expect_blob)
        if args.stdout_json_only:
            print(dumps_deterministic(projection), end="")
            return 0
        expected = {
            "projection.json": dumps_deterministic(projection).encode("utf-8"),
            "projection.txt": text.encode("utf-8"),
            "projection.html": page.encode("utf-8"),
            "CANDIDATE": (
                "candidate projection of a proposed-reference-view corpus map; "
                "not accepted, not a proof graph, not runtime policy, not Muneral state\n"
            ).encode("utf-8"),
        }
        if args.check:
            mismatches = []
            for name, content in sorted(expected.items()):
                path = args.out_dir / name
                if not path.is_file():
                    mismatches.append({"file": name, "error": "missing"})
                    continue
                actual = path.read_bytes()
                if actual != content:
                    mismatches.append({
                        "file": name,
                        "error": "digest_mismatch",
                        "expected_sha256": hashlib.sha256(content).hexdigest(),
                        "actual_sha256": hashlib.sha256(actual).hexdigest(),
                    })
            if mismatches:
                return refuse(ProjectionError(
                    "projection_check_mismatch",
                    "committed projection does not match fresh deterministic output",
                    {"mismatches": mismatches},
                ))
            digests = {name: hashlib.sha256(content).hexdigest() for name, content in sorted(expected.items())}
        else:
            digests = write_outputs(args.out_dir, projection, text, page)
        summary = {
            "ok": True,
            "status": CANDIDATE_STATUS,
            "input_blob": projection["input"]["blob"],
            "out_dir": args.out_dir.as_posix(),
            "counts": projection["counts"],
            "sha256": digests,
            "reading_link_cycle_components": len(projection["reading_link_cycles"]["components"]),
            "check": bool(args.check),
        }
        print(dumps_deterministic(summary), end="")
        return 0
    except ProjectionError as err:
        return refuse(err)
    except OSError as exc:
        return refuse(ProjectionError(REASON_INPUT_ERROR, str(exc)))


if __name__ == "__main__":
    raise SystemExit(main())
