    for e in projection["layers"]["relations"]:
        lines.append(f"  {e['from']} -[{e['kind']}]-> {e['to']}")
    lines.append("")
    lines.append("Layers: planning_requires")
    for e in projection["layers"]["planning_requires"]:
        lines.append(f"  {e['from']} -[requires]-> {e['to']}")
    lines.append("")
    return "\n".join(lines)


